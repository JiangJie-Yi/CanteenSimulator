/** a phrase put together of these (by '，', ended or not by '。') in another language: each piece looked up, joined as that language joins
 * them; a piece not in the table stays as it is */
export function peopleIn(text: string, lang: Lang, sentences = false) {
  if (lang === 'zh') return text
  const ended = text.endsWith('。')
  const bits = (ended ? text.slice(0, -1) : text).split('，'), k = lang === 'ja' ? 0 : 1
  // (a phrase with a comma of its own (家裡開小吃店，想多見識) tried whole before its halves)
  const parts: string[] = []
  for (let i = 0; i < bits.length; i++) {
    const two = i + 1 < bits.length ? PEOPLE_TEXT[`${bits[i]}，${bits[i + 1]}`] : undefined
    if (two) { parts.push(two[k]); i++ } else parts.push(PEOPLE_TEXT[bits[i]]?.[k] ?? bits[i])
  }
  if (lang === 'ja') return parts.join(sentences ? '。' : '、') + (ended ? '。' : '')
  return sentences ? parts.map((p) => p.replace(/\.$/, '')).join('. ') + '.' : parts.join(', ')
}
