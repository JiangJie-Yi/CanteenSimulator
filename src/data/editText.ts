/** a piece's name in the panel's language */
export function pieceName(zh: string, lang: Lang) {
  if (lang !== 'ja') return zh
  if (PIECES_JA[zh]) return PIECES_JA[zh]
  let s = zh
  for (const [a, b] of WORDS_JA) s = s.split(a).join(b)
  return s
}
